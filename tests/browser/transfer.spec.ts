import { test, expect } from '@playwright/test';
import { createHash } from 'node:crypto';

test('two isolated browsers pair, transfer verified bytes both ways, share text, reject, end room', async ({ browser }) => {
  const a = await browser.newContext(); const b = await browser.newContext();
  const host = await a.newPage(); const guest = await b.newPage();
  const errors: string[] = [];
  for (const page of [host, guest]) page.on('pageerror', error => errors.push(error.message));
  await host.goto('/app'); await expect(host).toHaveTitle('Your transfer room — Drop');
  await expect(host.locator('.send-panel .drop-zone .button')).toBeDisabled();
  const roomResponse = host.waitForResponse(response => response.url().endsWith('/api/rooms') && response.request().method() === 'POST');
  await host.getByRole('button', { name: 'Create a room' }).click();
  const createdRoom = await (await roomResponse).json();
  expect(createdRoom.expires - Date.now()).toBeGreaterThan(7_190_000);
  expect(createdRoom.expires - Date.now()).toBeLessThanOrEqual(7_200_000);
  const invite = host.getByRole('textbox', { name: 'Room invite' });
  await expect(invite).toBeVisible();
  await guest.goto(await invite.inputValue());
  await guest.getByRole('button', { name: 'Join', exact: true }).click();
  await expect(guest.getByText('One last hello.')).toBeVisible();
  await expect(host.getByLabel('Room name', {exact:true})).toHaveText(/^[A-HJ-NP-Z2-9]{4}$/);
  await expect(guest.getByLabel('Room name', {exact:true})).toHaveText(await host.getByLabel('Room name', {exact:true}).textContent() || '');
  await host.getByRole('button', { name: 'Allow device' }).click();
  await expect(host.getByLabel('Device verification code')).toHaveText(/^[A-F0-9]{4}( [A-F0-9]{4}){7}$/);
  await expect(guest.getByLabel('Device verification code')).toHaveText(await host.getByLabel('Device verification code').textContent() || '');
  await expect(host.locator('.send-panel .drop-zone .button')).toBeDisabled();
  await host.getByRole('button', { name: 'Codes match', exact: true }).click();
  await expect(host.locator('.send-panel .drop-zone .button')).toBeDisabled();
  await guest.getByRole('button', { name: 'Codes match', exact: true }).click();
  await expect(host.getByText('You’re connected.')).toBeVisible();
  await expect(guest.getByText('You’re connected.')).toBeVisible();
  await expect(host.getByLabel('Files sent', { exact: true })).toHaveText('0');
  await expect(guest.getByLabel('Files received', { exact: true })).toHaveText('0');
  await guest.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  await host.getByLabel('Choose file to send').setInputFiles({ name: 'blocked.exe', mimeType: 'application/octet-stream', buffer: Buffer.from('test') });
  await expect(host.getByRole('alert')).toContainText('Executable, script');
  await host.getByRole('button', { name: 'Dismiss message' }).click();
  await host.getByLabel('Choose file to send').setInputFiles({ name: 'renamed-photo.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('MZ-not-a-photo') });
  await expect(host.getByRole('alert')).toContainText('looks like a program');
  await host.getByRole('button', { name: 'Dismiss message' }).click();
  const payload = Buffer.alloc(1024 * 1024 + 37); for (let i = 0; i < payload.length; i++) payload[i] = i % 251;
  await host.getByLabel('Choose file to send').setInputFiles({ name: 'proof.bin', mimeType: 'application/octet-stream', buffer: payload });
  await expect(guest.getByRole('button', { name: 'Accept file', exact: true })).toBeInViewport();
  await expect(guest.getByRole('button', { name: 'Decline file', exact: true })).toBeInViewport();
  await guest.getByRole('button', { name: 'Accept file', exact: true }).click();
  await expect(host.getByText('Delivered', { exact: true })).toBeVisible();
  await expect(host.getByLabel('Files sent', { exact: true })).toHaveText('1');
  await expect(guest.getByLabel('Files received', { exact: true })).toHaveText('1');
  await host.locator('.send-panel').screenshot({path:'public/assets/actual-send.png'});
  await guest.setViewportSize({width:390,height:844});
  await guest.locator('.history').screenshot({path:'public/assets/actual-received.png'});
  const downloadPromise = guest.waitForEvent('download');
  await guest.getByRole('link', { name: 'Save file' }).click();
  const download = await downloadPromise;
  const stream = await download.createReadStream(); const chunks: Buffer[] = [];
  for await (const chunk of stream!) chunks.push(chunk);
  expect(createHash('sha256').update(Buffer.concat(chunks)).digest('hex')).toBe(createHash('sha256').update(payload).digest('hex'));
  await guest.getByLabel('Text & links', { exact: true }).fill('<script>alert(1)</script> https://example.com');
  await guest.getByRole('button', { name: 'Send note' }).click();
  await expect(host.locator('pre')).toHaveText('<script>alert(1)</script> https://example.com');
  const longNote = ('Hello 🌏 తెలుగు\n\u0001').repeat(4000).slice(0, 50_000);
  await expect(guest.getByLabel('Text & links', { exact: true })).toHaveAttribute('maxlength', '50000');
  await guest.getByLabel('Text & links', { exact: true }).fill(longNote);
  await guest.getByRole('button', { name: 'Send note' }).click();
  await expect.poll(() => host.locator('pre').first().textContent()).toBe(longNote);
  await expect(guest.locator('.transfer-row').first()).toContainText('Delivered');
  await guest.getByLabel('Choose file to send').setInputFiles({ name: 'empty.txt', mimeType: 'text/plain', buffer: Buffer.alloc(0) });
  await host.getByRole('button', { name: 'Accept file', exact: true }).click();
  await expect(host.getByRole('link', { name: 'Save file' })).toBeVisible();
  // HTML is transferred as an inert binary download, with its original name and bytes.
  await expect(guest.getByLabel('Files sent', { exact: true })).toHaveText('1');
  await expect(host.getByLabel('Files received', { exact: true })).toHaveText('1');
  await guest.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
  const html = Buffer.from('<!doctype html><title>My file</title><script>window.__htmlExecuted = true</script><h1>Hello</h1>');
  await host.getByLabel('Choose file to send').setInputFiles({ name: 'website.html', mimeType: 'text/html', buffer: html });
  await expect(guest.getByRole('button', { name: 'Accept file', exact: true })).toBeInViewport();
  await expect(guest.getByRole('button', { name: 'Decline file', exact: true })).toBeInViewport();
  expect(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await guest.screenshot({path: 'C:/Users/prana/AppData/Local/Temp/drop-incoming-mobile.png'});
  await guest.getByRole('button', { name: 'Accept file', exact: true }).click();
  const htmlRow = guest.locator('.transfer-row').filter({ hasText: 'website.html' });
  const saveHTML = htmlRow.getByRole('link', { name: 'Save file' });
  await expect(saveHTML).toBeVisible();
  const htmlDownloadPromise = guest.waitForEvent('download');
  await saveHTML.click();
  const htmlDownload = await htmlDownloadPromise;
  expect(htmlDownload.suggestedFilename()).toBe('website.html');
  const htmlStream = await htmlDownload.createReadStream(); const htmlChunks: Buffer[] = [];
  for await (const chunk of htmlStream!) htmlChunks.push(chunk);
  expect(Buffer.concat(htmlChunks).equals(html)).toBeTruthy();
  expect(await guest.evaluate(() => (window as Window & { __htmlExecuted?: boolean }).__htmlExecuted)).toBeUndefined();
  await expect(host.getByLabel('Files sent', { exact: true })).toHaveText('2');
  await expect(guest.getByLabel('Files received', { exact: true })).toHaveText('2');
  await host.getByLabel('Choose file to send').setInputFiles({ name: 'decline.txt', mimeType: 'text/plain', buffer: Buffer.from('no') });
  await guest.getByRole('button', { name: 'Decline file', exact: true }).click();
  await expect(host.getByText('Cancelled', { exact: true })).toBeVisible();
  await expect(host.getByLabel('Files sent', { exact: true })).toHaveText('2');
  await guest.getByRole('button', { name: 'End room' }).click();
  await expect(host.getByRole('button', { name: 'Create a room' })).toBeVisible();
  expect(errors).toEqual([]);
  await a.close(); await b.close();
});

test('rejecting mismatched device codes closes the room without enabling transfers', async ({ browser }) => {
  const a = await browser.newContext(); const b = await browser.newContext();
  const host = await a.newPage(); const guest = await b.newPage();
  await host.goto('/app'); await host.getByRole('button', { name: 'Create a room' }).click();
  const invite = host.getByRole('textbox', { name: 'Room invite' }); await expect(invite).toBeVisible();
  await guest.goto(await invite.inputValue()); await guest.getByRole('button', { name: 'Join', exact: true }).click();
  await host.getByRole('button', { name: 'Allow device' }).click();
  await host.getByRole('button', { name: 'Codes do not match' }).click();
  await expect(host.getByRole('alert')).toContainText('Nothing was transferred');
  await expect(guest.getByRole('button', { name: 'Create a room' })).toBeVisible();
  await expect(guest.locator('.send-panel .drop-zone .button')).toBeDisabled();
  await a.close(); await b.close();
});

